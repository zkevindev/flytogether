import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { join } from 'node:path';
assert.ok(process.env.QA_BASE_URL,'Set QA_BASE_URL');
const output=process.env.QA_OUTPUT_DIR||'test-results/pages';await mkdir(output,{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true,args:process.platform==='darwin'?['--use-angle=metal']:[]});
try{
 const page=await browser.newPage({baseURL:process.env.QA_BASE_URL,viewport:{width:1440,height:1120}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(()=>{localStorage.setItem('fly-auto-voice','off');localStorage.setItem('fly-host-voice','off');});
 await page.goto(process.env.QA_BASE_URL,{waitUntil:'networkidle'});
 assert.equal(await page.locator('.flight-host').count(),0,'home has no board');
 assert.equal(await page.locator('.voice-panel').count(),0,'home has no active voice panel');
 await page.screenshot({path:join(output,'home.png')});
 await page.getByRole('button',{name:'创建游戏',exact:true}).click();
 const setup=page.getByRole('dialog',{name:'创建家庭房间'});
 await setup.getByLabel('房间名称',{exact:true}).fill('亲子测试机场');
 await setup.getByRole('checkbox',{name:/邀请灵矽加入/}).uncheck();
 await setup.getByRole('button',{name:'4 位',exact:true}).click();
 const names=await setup.locator('.name-fields input').evaluateAll(nodes=>nodes.map(node=>node.value));assert.equal(new Set(names).size,4);
 await setup.getByRole('button',{name:'2 位',exact:true}).click();
 await setup.getByRole('button',{name:'创建并开始游戏',exact:true}).click();
 await page.waitForURL('**/play');await page.locator('.flight-host canvas').waitFor({state:'visible'});
 assert.equal(await page.locator('.page-intro,.log-panel,.turn-panel').count(),0);
 const board=await page.locator('.flight-host').boundingBox();assert.ok(board.width>=850,'desktop board is large');
 let room=(await(await page.request.get('/api/session')).json()).room;const id=room.state.id;const initialVersion=room.state.version;
 assert.equal(room.status,'playing');
 await page.screenshot({path:join(output,'play-desktop.png'),fullPage:true});
 await page.reload({waitUntil:'networkidle'});await page.locator('.flight-host canvas').waitFor({state:'visible'});
 assert.equal((await(await page.request.get('/api/session')).json()).room.state.id,id);
 await page.getByRole('button',{name:/道具口袋/}).click();
 await page.getByRole('button',{name:'使用起飞卡',exact:true}).click();
 await page.getByRole('dialog').waitFor({state:'hidden'});
 await page.locator('.roll-button').click();
 await page.getByRole('dialog',{name:'3D 掷骰结果'}).waitFor({state:'visible'});
 await page.getByRole('button',{name:'继续飞行',exact:true}).click();
 await page.getByRole('button',{name:'小熊号',exact:true}).click();
 await page.waitForFunction(version=>document.querySelector('.flight-board')?.dataset.version===String(version),initialVersion+3);
 room=(await(await page.request.get('/api/session')).json()).room;assert.equal(room.state.players[0].pieces[0].progress,0);
 await page.getByRole('button',{name:'返回首页',exact:true}).click();await page.waitForURL(new URL('/',process.env.QA_BASE_URL).href);
 await page.waitForFunction(()=>!document.querySelector('.flight-host'));
 await page.getByRole('button',{name:/继续当前游戏/}).click();await page.waitForURL('**/play');
 await page.locator('.game-status-overlay').waitFor({state:'hidden'});
 await page.waitForFunction(()=>!document.querySelector('.roll-button')?.disabled);
 await page.setViewportSize({width:390,height:844});
 await page.locator('.flight-host').waitFor({state:'visible'});
 const dimensions=await page.evaluate(()=>({width:document.documentElement.clientWidth,scroll:document.documentElement.scrollWidth,board:document.querySelector('.flight-host').getBoundingClientRect().width}));
 assert.ok(dimensions.scroll<=dimensions.width);assert.ok(dimensions.board>=360);
 await page.screenshot({path:join(output,'play-mobile.png'),fullPage:true});
 assert.equal((await(await page.request.get('/api/session')).json()).room.state.id,id);
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({result:'PASS',desktop_board_width:board.width,mobile_board_width:dimensions.board,scope:'create -> /play -> refresh -> prop -> random roll -> takeoff -> home pause -> resume; no page overflow or console errors'}));
}finally{await browser.close();}
