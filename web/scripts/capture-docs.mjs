import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { createHash } from 'node:crypto';
assert.ok(process.env.QA_BASE_URL && process.env.QA_SOURCE_COMMIT, 'Set QA_BASE_URL and QA_SOURCE_COMMIT to the running app commit');
const output=resolve(process.env.QA_OUTPUT_DIR||'test-results/docs');await mkdir(output,{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true,args:process.platform==='darwin'?['--use-angle=metal']:[]});
const captures=[],errors=[];
try{
 const page=await browser.newPage({baseURL:process.env.QA_BASE_URL,viewport:{width:1440,height:1120},deviceScaleFactor:1});
 page.on('pageerror',e=>errors.push(e.message));
 page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
 await page.addInitScript(()=>{
 localStorage.setItem('fly-tutorial-v1','skipped');
  localStorage.setItem('fly-auto-voice','off');localStorage.setItem('fly-host-voice','off');
  window.__docsMicrophone=0;
  navigator.mediaDevices.getUserMedia=async()=>{window.__docsMicrophone++;throw new Error('Documentation screenshots never need a microphone');};
 });
 const capture=async(name,target=page)=>{
  await page.evaluate(()=>document.fonts.ready);
  await target.screenshot({path:join(output,name),...(target===page?{fullPage:true}:{})});
  const viewport=page.viewportSize();const bytes=await readFile(join(output,name));
  captures.push({file:name,viewport,sha256:createHash('sha256').update(bytes).digest('hex')});
 };
 const settle=async()=>{
  await page.locator('.flight-host canvas').waitFor({state:'visible'});
  await page.waitForTimeout(600);
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>document.documentElement.clientWidth);
  assert.equal(overflow,false,'screenshots should not hide page overflow');
 };
 await page.goto(process.env.QA_BASE_URL,{waitUntil:'networkidle'});
 await page.getByRole('button',{name:'创建游戏',exact:true}).waitFor({state:'visible'});
 assert.equal(await page.locator('.flight-host').count(),0);
 assert.equal(await page.getByText('一张棋盘，开口就能一起玩。',{exact:false}).count(),1);
 await capture('home.png');
 await page.getByRole('button',{name:'创建游戏',exact:true}).click();
 const setup=page.getByRole('dialog',{name:'创建家庭房间'});
 await setup.getByLabel('房间名称',{exact:true}).fill('周末家庭机场');
 await setup.getByRole('checkbox',{name:/邀请灵矽加入/}).uncheck();
 await setup.getByRole('button',{name:'2 位',exact:true}).click();
 await capture('setup.png',setup);
 await setup.getByRole('button',{name:'创建并开始游戏',exact:true}).click();
 await page.waitForURL('**/play');await settle();
 await capture('play-desktop.png');
 await page.getByRole('button',{name:'新手指南',exact:true}).click();
 await capture('onboarding.png',page.getByRole('dialog',{name:'新手飞行指南'}));
 await page.getByRole('button',{name:'跳过新手引导',exact:true}).click();
 await page.getByRole('button',{name:/道具口袋/}).click();
 await capture('props.png',page.getByRole('dialog'));
 await page.getByRole('button',{name:'使用起飞卡',exact:true}).click();
 await page.locator('.roll-button').click();
 const dice=page.getByRole('dialog',{name:'3D 掷骰结果'});
 await dice.getByRole('heading',{name:/点！/}).waitFor({state:'visible'});
 await capture('dice-3d.png',dice);
 await dice.getByRole('button',{name:'继续飞行',exact:true}).click();
 await page.getByRole('button',{name:'小熊号',exact:true}).click();
 await page.locator('.landing-marker:not([hidden])').waitFor({state:'visible'});
 await capture('move-preview.png');
 await page.getByRole('button',{name:'确认飞行',exact:true}).click();
 await page.waitForFunction(()=>!document.querySelector('.roll-button')?.disabled);
 await settle();
 const room=(await(await page.request.get('/api/session')).json()).room;
 assert.equal(room.state.players[0].pieces[0].progress,0);
 await page.setViewportSize({width:390,height:844});await settle();
 await capture('play-mobile.png');
 assert.equal(await page.evaluate(()=>window.__docsMicrophone),0);
 assert.deepEqual(errors,[]);
 await writeFile(join(output,'manifest.json'),JSON.stringify({captured_at:new Date().toISOString(),app_commit:process.env.QA_SOURCE_COMMIT,browser:browser.version(),scope:'Actual app UI: home, create, board, five props, random dice and takeoff; two human seats; voice switched off; no mocked state or microphone',captures,console_errors:0,microphone_requests:0},null,2)+'\n');
 console.log(JSON.stringify({result:'PASS',screenshots:captures.length,console_errors:errors.length,microphone_requests:0,app_commit:process.env.QA_SOURCE_COMMIT}));
}finally{await browser.close();}
