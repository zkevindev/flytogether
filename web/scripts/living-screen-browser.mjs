await mkdir(out, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: process.platform === 'darwin' ? ['--use-angle=metal'] : [] });
const contexts = [], errors = [], results = [];
const wait = async (fn, label, timeout = 20000) => { const start = Date.now(); while (Date.now() - start < timeout) { if (await fn()) return; await new Promise(r => setTimeout(r, 100)); } throw Error(label); };
const context = async (viewport = { width: 1360, height: 900 }) => {
  const c = await browser.newContext({ baseURL: base, viewport }); contexts.push(c);
  await c.addInitScript(() => {
    localStorage.setItem('fly-auto-voice', 'off'); localStorage.setItem('fly-host-voice', 'off'); localStorage.setItem('fly-tutorial-v1', 'skipped'); localStorage.setItem('fly-experience', JSON.stringify({ board: 'flat', motion: 'reduced' }));
    window.__screen = { mic: 0, snapshot: null };
    navigator.mediaDevices.getUserMedia = async () => { window.__screen.mic++; throw new DOMException('blocked by living screen test', 'NotAllowedError'); };
    const WS = WebSocket; window.WebSocket = class extends WS { constructor(url, ...args) { super(url, ...args); if (String(url).includes('/ws/game?')) this.addEventListener('message', event => { if (typeof event.data === 'string') { const data = JSON.parse(event.data); if (data.type === 'state') window.__screen.snapshot = data.room; } }); } };
  });
  return c;
};
const page = async (c, path) => { const p = await c.newPage(); p.setDefaultTimeout(20000); p.on('pageerror', e => errors.push(e.message)); await p.goto(path, { waitUntil: 'networkidle' }); return p; };
const session = async c => (await (await c.request.get('/api/session')).json()).room;
const post = async (c, path, data, expected = 200) => { const res = await c.request.post(path, { data }); const value = await res.json(); assert.equal(res.status(), expected, JSON.stringify(value)); return value; };
